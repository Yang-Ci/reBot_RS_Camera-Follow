"""Contracts for devices used by control and runtime code."""
from __future__ import annotations

from typing import Any, Protocol

import numpy as np


class RobotControl(Protocol):
    """Six-axis arm and gripper operations; angles are radians unless noted."""
    q_min: np.ndarray
    q_max: np.ndarray
    recovery_max_speed: float

    def get_current_pos(self) -> np.ndarray: ...
    def get_command_pos(self) -> np.ndarray: ...
    def joint_vel_cmd(self, velocity: np.ndarray) -> None: ...
    def tcp_pose_and_jacobian(self, joints: np.ndarray, tool_offset: np.ndarray
                              ) -> tuple[np.ndarray, np.ndarray, np.ndarray]: ...
    def forward_kinematics(self) -> dict[str, np.ndarray]: ...
    def move_to_joints(self, joints: np.ndarray, **options: Any) -> None: ...
    def set_joint_speed_cap(self, speed_deg_s: float) -> None: ...
    def get_gripper_deg(self) -> float: ...
    def get_gripper_command_deg(self) -> float: ...
    def set_gripper_deg(self, degrees: float) -> None: ...
    def hold(self) -> None: ...
    def is_stopping(self) -> bool: ...
    def stop(self) -> None: ...
